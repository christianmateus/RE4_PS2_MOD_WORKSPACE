    public static IReadOnlyList<EtmResource> Resources(EtmCatalog catalog,byte id)
    {
        if(!catalog.Objects.TryGetValue(id,out var definition))return Array.Empty<EtmResource>();
        var referenced=Names.TryGetValue(id,out var names)?names:Array.Empty<string>();
        return definition.Resources.Concat(catalog.Resources.Where(r=>referenced.Contains(r.Name,StringComparer.OrdinalIgnoreCase))).DistinctBy(r=>r.FileOrder).OrderBy(r=>r.FileOrder).ToArray();
    }
